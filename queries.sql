-- Calculer la somme de tous les paiements enregistrés dans la table Payments --
-- En: Calculate the total amount of all payments recorded in the Payments table --
SELECT SUM(amount_paid) AS total_revenue
FROM Payments;

-- Pour chaque facture, connaître son montant total, le montant déjà payé et le montant qui reste à régler --
-- En : Identify the total invoice amount, the amount already paid, and the remaining balance to be paid for each invoice --
SELECT
  i.invoice_id,
  i.total_amount,
  COALESCE(SUM(p.amount_paid), 0) AS paid_amount,
  (i.total_amount - COALESCE(SUM(p.amount_paid), 0)) AS outstanding
FROM Invoices i
LEFT JOIN Payments p ON i.invoice_id = p.invoice_id
GROUP BY i.invoice_id;

-- Savoir combien de ventes ont été réalisées pour chaque produit à partir des articles enregistrés dans les commandes --
-- En : Determine the total sales value generated by each product based on the order items recorded in the system --
SELECT 
  p.name,
  SUM(oi.quantity * oi.unit_price) AS total_sales
FROM Order_Items oi
JOIN Products p ON oi.product_id = p.product_id
GROUP BY p.name;

-- Consulter les quantités disponibles en stock pour chaque produit --
-- En : Retrieve the current recorded stock quantity for each product --
SELECT 
  name,
  stock_quantity
FROM Products;

-- Calculer le montant total des paiements enregistrés pour chaque client --
-- Determine the total amount of payments recorded for each customer -- 
SELECT 
  c.name,
  SUM(p.amount_paid) AS total_spent
FROM Payments p
JOIN Invoices i ON p.invoice_id = i.invoice_id
JOIN Orders o ON i.order_id = o.order_id
JOIN Customers c ON o.customer_id = c.customer_id
GROUP BY c.name;

-- Connaître le montant total des paiements enregistrés à chaque date --
-- Calculate the total amount of payments recorded on each date, in chronological order --
SELECT 
  payment_date,
  SUM(amount_paid) AS daily_revenue
FROM Payments
GROUP BY payment_date
ORDER BY payment_date;

